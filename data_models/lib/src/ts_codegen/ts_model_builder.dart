import 'package:build/build.dart';

import 'ts_analytics_generator.dart';
import 'ts_model_generator.dart';

const _header = "import { z } from 'zod';\n\n";

/// Prototype builder: walks every library in `data_models/lib`, finds
/// `@Freezed` classes and plain `@JsonSerializable()` classes, and emits a
/// sibling `.model.ts` file with a zod schema per class. One output file per
/// input `.dart` file (matching how `.freezed.dart`/`.g.dart` are already
/// laid out), not one per class.
///
/// Known gaps in this first pass (see TODO markers in generated output):
/// - Cross-file `@JsonKey(toJson: OtherClass.staticMethod)` references.
/// - Nested-model imports are stubbed with `z.lazy()` and a TODO comment
///   rather than real import statements.
class TsModelBuilder implements Builder {
  final _freezedGenerator = TsModelGenerator();
  final _analyticsGenerator = TsAnalyticsGenerator();

  @override
  Map<String, List<String>> get buildExtensions => {
        '.dart': ['.model.ts'],
      };

  @override
  Future<void> build(BuildStep buildStep) async {
    if (!await buildStep.resolver.isLibrary(buildStep.inputId)) {
      return; // part files (.freezed.dart/.g.dart) aren't standalone libraries
    }

    final library = await buildStep.inputLibrary;
    final outputs = <String>[];
    var anyFollowUp = false;

    // Only the defining unit (the input .dart file itself), not `library.units`
    // - freezed's generated `part` files (.freezed.dart) declare a private
    // implementation class that it annotates with `@JsonSerializable()` for
    // its own tooling purposes, which would otherwise be misdetected here as
    // a second, separate analytics-style model.
    for (final classElement in library.definingCompilationUnit.classes) {
      final result = _freezedGenerator.generateForClass(classElement) ??
          _analyticsGenerator.generateForClass(classElement);
      if (result == null) continue;
      outputs.add(result.ts);
      anyFollowUp = anyFollowUp || result.needsManualFollowUp;
    }

    if (outputs.isEmpty) return;

    final banner = anyFollowUp
        ? '// GENERATED BY ts_model_builder (prototype) - contains TODOs, needs review\n\n'
        : '// GENERATED BY ts_model_builder (prototype)\n\n';

    final outputId = buildStep.inputId.changeExtension('.model.ts');
    await buildStep.writeAsString(
      outputId,
      banner + _header + outputs.join('\n'),
    );
  }
}

Builder tsModelBuilder(BuilderOptions options) => TsModelBuilder();
